export const FONT_HEIGHT = 7;
/** Blank pixel columns inserted between two glyphs. */
export const FONT_TRACKING = 1;
/** Width of the space character, in pixels. */
export const FONT_SPACE = 3;

export interface Glyph {
  /** Bitmap columns, left-trimmed and right-trimmed. */
  rows: string[];
  width: number;
}

function trim(rows: string[]): Glyph {
  let first = 5;
  let last = -1;
  for (const row of rows) {
    for (let x = 0; x < row.length; x++) {
      if (row[x] === '1') {
        if (x < first) first = x;
        if (x > last) last = x;
      }
    }
  }
  if (last < 0) return { rows: rows.map(() => ''), width: FONT_SPACE };
  return {
    rows: rows.map((row) => row.slice(first, last + 1)),
    width: last - first + 1,
  };
}

const CACHE = new Map<string, Glyph>();

/** Returns the (trimmed) bitmap for a character, or `null` when unsupported. */
export function glyphOf(ch: string): Glyph | null {
  const key = ch.toUpperCase();
  const cached = CACHE.get(key);
  if (cached) return cached;
  const raw = GLYPHS[key];
  if (!raw) return null;
  const g = trim(raw);
  CACHE.set(key, g);
  return g;
}

/** Advance width of a single character including tracking. */
export function charWidth(ch: string): number {
  if (ch === ' ') return FONT_SPACE + FONT_TRACKING;
  if (ch === '\t') return FONT_SPACE * 2 + FONT_TRACKING;
  const g = glyphOf(ch);
  if (!g) return FONT_SPACE + FONT_TRACKING;
  return g.width + FONT_TRACKING;
}

/** Pixel width of a string rendered with this font (trailing tracking removed). */
export function measure(text: string): number {
  let w = 0;
  for (const ch of text) w += charWidth(ch);
  return Math.max(0, w - FONT_TRACKING);
}

/** Greedily wraps `text` so that no rendered line exceeds `maxWidth` pixels. */
export function wrap(text: string, maxWidth: number): string[] {
  const out: string[] = [];
  for (const paragraph of text.split('\n')) {
    if (paragraph === '') {
      out.push('');
      continue;
    }
    let line = '';
    for (const word of paragraph.split(' ')) {
      const candidate = line === '' ? word : `${line} ${word}`;
      if (measure(candidate) <= maxWidth || line === '') {
        line = candidate;
      } else {
        out.push(line);
        line = word;
      }
    }
    out.push(line);
  }
  return out;
}
